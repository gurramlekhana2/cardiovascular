"""
Inference & Prediction Pipeline Module for Cardiovascular Disease Prediction System.

Loads serialized model artifacts, applies domain feature engineering,
and performs calibrated risk probability scoring with optimized clinical screening thresholds.
Contains explicit academic decision-support disclaimer and per-patient XAI factor breakdowns.
"""

import os
import sys
import joblib
import pandas as pd
import numpy as np

# Ensure project root directory is in sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.feature_engineering import add_engineered_features
from src.explainability import explain_single_patient

MODEL_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), "../models/final_model.pkl"))
METADATA_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), "../models/model_metadata.joblib"))


class CardiovascularRiskPredictor:
    """
    Inference interface for loading trained model artifacts and predicting CVD risk.
    """

    def __init__(self, model_file: str = MODEL_PATH):
        if not os.path.exists(model_file):
            raise FileNotFoundError(f"Model file not found at {model_file}. Run run_pipeline.py first.")
        self.model = joblib.load(model_file)

        # Load metadata if available, else default to clinically cautious 0.45 threshold
        self.optimal_threshold = 0.45
        if os.path.exists(METADATA_PATH):
            try:
                meta = joblib.load(METADATA_PATH)
                self.optimal_threshold = meta.get('optimal_threshold', 0.45)
            except Exception:
                pass

    def predict_patient(self, patient_dict: dict, threshold_override: float = None) -> dict:
        """
        Takes raw patient clinical parameters, applies feature engineering,
        and returns prediction metrics with cautious academic risk language and local explanations.
        """
        df = pd.DataFrame([patient_dict])

        # Convert age to days if provided in years
        if 'age' not in df.columns and 'age_years' in df.columns:
            df['age'] = (df['age_years'] * 365.25).astype(int)

        # Apply Feature Engineering
        df_engineered = add_engineered_features(df)

        expected_cols = [
            'age', 'height', 'weight', 'ap_hi', 'ap_lo',
            'gender', 'cholesterol', 'gluc', 'smoke', 'alco', 'active',
            'age_years', 'bmi', 'pulse_pressure', 'map', 'bp_category', 'bmi_category',
            'age_map_interaction', 'chol_gluc_interaction', 'lifestyle_risk'
        ]
        df_input = df_engineered[expected_cols]

        # Predict probability
        if hasattr(self.model, "predict_proba"):
            prob = float(self.model.predict_proba(df_input)[0, 1])
        else:
            prob = float(self.model.decision_function(df_input)[0])

        prob_pct = round(prob * 100, 1)

        # Apply optimized threshold for higher healthcare sensitivity
        cutoff = threshold_override if threshold_override is not None else self.optimal_threshold
        pred_class = 1 if prob >= cutoff else 0

        if prob >= cutoff:
            risk_category = "Elevated Cardiovascular Risk Detected"
            risk_color = "red"
        else:
            risk_category = "Low / Baseline Cardiovascular Risk"
            risk_color = "green"

        # Local factor contributions (SHAP)
        explanations_df = explain_single_patient(self.model, df_input)

        disclaimer = (
            "ACADEMIC DISCLAIMER: This risk assessment is generated by an academic machine learning decision-support "
            "model for educational and research purposes only. It does NOT constitute a clinical diagnosis or medical "
            "advice. Consult a qualified physician for clinical evaluation."
        )

        return {
            'predicted_class': pred_class,
            'risk_category': risk_category,
            'risk_color': risk_color,
            'probability': prob,
            'probability_pct': prob_pct,
            'decision_threshold': cutoff,
            'disclaimer': disclaimer,
            'explanations': explanations_df,
            'engineered_features': {
                'bmi': float(df_engineered['bmi'].iloc[0]),
                'pulse_pressure': int(df_engineered['pulse_pressure'].iloc[0]),
                'map': float(df_engineered['map'].iloc[0]),
                'bp_category': int(df_engineered['bp_category'].iloc[0]),
                'bmi_category': int(df_engineered['bmi_category'].iloc[0]),
                'age_map_interaction': float(df_engineered['age_map_interaction'].iloc[0]),
                'lifestyle_risk': int(df_engineered['lifestyle_risk'].iloc[0])
            }
        }


if __name__ == "__main__":
    predictor = CardiovascularRiskPredictor()
